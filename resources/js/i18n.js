/* ------------------------------------------------------------------ */
/* Krotze i18n — gettext-style: the English text is the key.           */
/*                                                                      */
/* t('Create channel') looks the string up in the active language's     */
/* dictionary and falls back to the key itself, so a missing entry      */
/* shows English rather than breaking. Placeholders are :name-style     */
/* and substituted after lookup. The language comes from localStorage   */
/* (the in-app selector) or the browser, and mirrors the languages of   */
/* the public site (config/app.php site_locales).                       */
/* ------------------------------------------------------------------ */

export const LANGS = {
    en: 'English',
    de: 'Deutsch',
    es: 'Español',
    fr: 'Français',
    zh: '中文',
    ar: 'العربية',
    fa: 'فارسی',
};

const LANG_KEY = 'krotze_lang';

let current = null;

export function getLang() {
    if (current) return current;
    let stored = null;
    try { stored = localStorage.getItem(LANG_KEY); } catch { /* storage blocked */ }
    if (stored && LANGS[stored]) return (current = stored);
    for (const candidate of navigator.languages || [navigator.language || 'en']) {
        const code = String(candidate).slice(0, 2).toLowerCase();
        if (LANGS[code]) return (current = code);
    }
    return (current = 'en');
}

const RTL = new Set(['ar', 'fa']);

/** Writing direction of the active language — drives <html dir>. */
export function dir() {
    return RTL.has(getLang()) ? 'rtl' : 'ltr';
}

export function setLang(code) {
    if (!LANGS[code]) return;
    current = code;
    try { localStorage.setItem(LANG_KEY, code); } catch { /* storage blocked */ }
}

export function t(text, params = null) {
    let out = (DICTS[getLang()] || {})[text] ?? text;
    if (params) {
        for (const [key, value] of Object.entries(params)) {
            out = out.replaceAll(':' + key, String(value));
        }
    }
    return out;
}

